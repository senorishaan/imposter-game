function writeCategoryFile(categoryId) {
  const words = wordsByCategory[categoryId];
  const pool = POOLS[categoryId];
  const overrides = OVERRIDES[categoryId] ?? {};
  const map = {};

  for (const word of words) {
    let hints = overrides[word];
    if (!hints?.length) {
      hints = [pickFromPool(word, pool)];
    }
    const valid = hints.filter((h) => !/\s/.test(h) && !isGiveaway(word, h));
    if (!valid.length) {
      valid.push(pickFromPool(word + "x", pool));
    }
    map[word] = valid.slice(0, 2);
  }

  const lines = [
    "/** @type {Record<string, string[]>} */",
    "export default {",
  ];
  for (const word of words) {
    lines.push(`  ${JSON.stringify(word)}: ${JSON.stringify(map[word])},`);
  }
  lines.push("};", "");

  const outPath = path.join(__dirname, "hints", `${categoryId}.mjs`);
  fs.writeFileSync(outPath, lines.join("\n"));
  console.log(`Wrote ${categoryId}: ${words.length} words`);
}

for (const cat of ["sports", "jobs", "objects", "nature"]) {
  writeCategoryFile(cat);
}
