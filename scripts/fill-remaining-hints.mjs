function normalize(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function tokens(text) {
  return normalize(text).split(" ").filter((t) => t.length > 2);
}

function isGiveaway(answer, hint) {
  const a = normalize(answer);
  const h = normalize(hint);
  if (!a || !h) return true;
  if (a === h) return true;
  for (const at of tokens(answer)) {
    for (const ht of tokens(hint)) {
      if (at === ht) return true;
      if (at.length >= 4 && ht.includes(at)) return true;
      if (ht.length >= 4 && at.includes(ht)) return true;
    }
  }
  if (h.length >= 4 && a.includes(h)) return true;
  if (a.length >= 4 && h.includes(a)) return true;
  return false;
}

function hashCode(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) h = (Math.imul(31, h) + str.charCodeAt(i)) | 0;
  return Math.abs(h);
}

function pickFromPool(word, pool) {
  const start = hashCode(word) % pool.length;
  for (let i = 0; i < pool.length; i++) {
    const hint = pool[(start + i) % pool.length];
    if (!isGiveaway(word, hint)) return hint;
  }
  return "ambiguous";
}

