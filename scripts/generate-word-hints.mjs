/**
 * Builds lib/wordHints.ts from scripts/words-by-category.json + scripts/hint-map.json
 * Run: node scripts/generate-word-hints.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const wordsByCategory = JSON.parse(
  fs.readFileSync(path.join(__dirname, "words-by-category.json"), "utf8"),
);
const hintMap = JSON.parse(
  fs.readFileSync(path.join(__dirname, "hint-map.json"), "utf8"),
);

const allWords = [...new Set(Object.values(wordsByCategory).flat())];
const missing = allWords.filter((w) => !hintMap[w]?.length);

if (missing.length > 0) {
  console.error(`Missing hints for ${missing.length} words:`, missing.slice(0, 20));
  process.exit(1);
}

const lines = [
  "// Auto-generated by scripts/generate-word-hints.mjs — do not edit by hand",
  "",
  "export const HINTS_BY_ANSWER: Record<string, readonly string[]> = {",
];

for (const word of [...allWords].sort()) {
  const hints = hintMap[word];
  const escaped = JSON.stringify(hints);
  lines.push(`  ${JSON.stringify(word)}: ${escaped},`);
}

lines.push("};", "");
lines.push("export function pickHintForAnswer(answer: string): string | null {");
lines.push("  const hints = HINTS_BY_ANSWER[answer];");
lines.push("  if (!hints?.length) return null;");
lines.push("  return hints[Math.floor(Math.random() * hints.length)]!;");
lines.push("}", "");

fs.writeFileSync(path.join(root, "lib", "wordHints.ts"), lines.join("\n"));
console.log(`Wrote ${allWords.length} word hints to lib/wordHints.ts`);
